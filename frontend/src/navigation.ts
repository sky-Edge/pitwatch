/**
 * 页面间导航的附加信息。
 *
 * 场景：项目列表的「需要关注」列出"哪个项目、哪一天、哪个测点出了问题"，
 * 点「去处理」应当**直接落到那条记录上**，而不是只把用户丢到某个页面。
 * 早先的实现不带这个信息，结果点了"已有 4 天没观测（上次 2026-09-24）"
 * 会落在"今天"的空表上 —— 也就定位不到问题日期。
 */

/** 定位到观测记录页的某一天 / 某个测点 */
export interface RecordsFocus {
  /** 要定位到的观测日期（YYYY-MM-DD） */
  date: string
  /**
   * 要额外高亮并滚动到的测点（可选；"该观测了"这类只定位日期）。
   * 用**测点编号**而不是内部 id：编号项目内唯一，
   * 且预警汇总、数据质量两处的返回结构里都只有编号（质量项没有 id）。
   */
  pointNo?: string
  /** 顶部提示语，说明"为什么把你带到这一天"（口语化，别写内部术语） */
  note?: string
}
